#!/usr/bin/env python3
"""Build responsive WebP sources from the original demo screenshots.

Run after changing screenshots: python3 scripts/optimize-demo-previews.py
Authoring dependency: Pillow 11.3+ with WebP support (python3 -m pip install Pillow).
No Python/image dependency is needed when building or deploying the website.
The JPEGs remain untouched as fallback/originals. Generated names hash the encoded
bytes, so the Worker can safely cache them without making later edits stale.
"""

import hashlib
import io
import json
import re
from pathlib import Path

from PIL import Image, features

ROOT = Path(__file__).resolve().parent.parent
PREVIEWS = ROOT / "public/demo/_previews"
SNIPPET = ROOT / "site/theme/snippets/demo-sources.liquid"
MANIFEST = ROOT / "site/demo-previews.json"
SHOTS = ("holm-tomrer", "salon-nord", "lervaerk", "salon-nord-booking", "lervaerk-produkt", "lervaerk-kurv")
QUALITY = 88


def variants(source, widths, stem):
    image = Image.open(PREVIEWS / source).convert("RGB")
    source_bytes = (PREVIEWS / source).stat().st_size
    rows = []
    for width in widths:
        height = round(image.height * width / image.width)
        resized = image.resize((width, height), Image.Resampling.LANCZOS)
        encoded = io.BytesIO()
        resized.save(encoded, format="WEBP", quality=QUALITY, method=6)
        data = encoded.getvalue()
        # Some already-optimized ceramic/mobile JPEGs are more efficient than
        # WebP at this quality. Keep their original rather than sending more.
        if len(data) >= source_bytes * .9:
            continue
        digest = hashlib.sha256(data).hexdigest()[:12]
        name = f"{stem}-{width}.{digest}.webp"
        (PREVIEWS / name).write_bytes(data)
        rows.append({"file": name, "width": width, "height": height, "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()})
    return {"source": source, "source_bytes": source_bytes, "variants": rows}


def srcset(group):
    return ", ".join(f'/demo/_previews/{row["file"]} {row["width"]}w' for row in group["variants"])


def build():
    if not features.check("webp"):
        raise SystemExit("Pillow needs WebP support to regenerate demo previews.")
    previous = json.loads(MANIFEST.read_text(encoding="utf-8")) if MANIFEST.exists() else {"screenshots": {}}
    previous_files = {row["file"] for shot in previous["screenshots"].values() for group in shot.values() for row in group["variants"]}
    manifest = {"quality": QUALITY, "screenshots": {}}
    lines = [
        "{%- comment -%}Generated by scripts/optimize-demo-previews.py. Keep JPEG fallback after these sources. Params: shot, sizes, mobile (optional), mobile_breakpoint (default 599px).{%- endcomment -%}",
        "{%- case shot -%}",
    ]
    for name in SHOTS:
        desktop = variants(f"{name}-1920.jpg", (480, 768, 960, 1920), name)
        mobile = variants(f"{name}-mobil.jpg", (480, 780), f"{name}-mobil")
        manifest["screenshots"][name] = {"desktop": desktop, "mobile": mobile}
        lines.append(f"{{%- when '{name}' -%}}")
        if mobile["variants"]:
            lines.extend([
                "{%- if mobile -%}",
                f'<source type="image/webp" media="(max-width: {{{{ mobile_breakpoint | default: \'599px\' }}}})" srcset="{srcset(mobile)}" sizes="{{{{ sizes }}}}" width="780" height="1280">',
                "{%- endif -%}",
            ])
        lines.extend([
            f'<source type="image/webp"{{% if mobile %}} media="(min-width: {{{{ desktop_breakpoint | default: \'600px\' }}}})"{{% endif %}} srcset="{srcset(desktop)}" sizes="{{{{ sizes }}}}" width="1920" height="1200">',
        ])
    phone = variants("holm-tomrer-phone-780.jpg", (390, 780), "holm-tomrer-phone")
    manifest["screenshots"]["holm-tomrer-phone"] = {"phone": phone}
    lines.extend([
        "{%- when 'holm-tomrer-phone' -%}",
        f'<source type="image/webp" srcset="{srcset(phone)}" sizes="{{{{ sizes }}}}" width="780" height="1688">',
        "{%- endcase -%}",
    ])
    SNIPPET.write_text("\n".join(lines) + "\n", encoding="utf-8")
    MANIFEST.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    # Only clean files owned by this generator; never alter original JPEGs.
    active = {row["file"] for shot in manifest["screenshots"].values() for group in shot.values() for row in group["variants"]}
    for name in previous_files - active:
        if re.fullmatch(r"[a-z0-9-]+\.[a-f0-9]{12}\.webp", name):
            (PREVIEWS / name).unlink(missing_ok=True)
    for name, shot in manifest["screenshots"].items():
        print(name, {kind: {row["width"]: row["bytes"] for row in group["variants"]} for kind, group in shot.items()})


if __name__ == "__main__":
    build()
