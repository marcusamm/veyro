"""Bounded, encrypted server-side storage for explicitly remembered mail logins.

The browser holds only a random bearer token. The database holds its SHA-256
digest, a keyed account index, and a Fernet-authenticated encrypted payload.
The separate deployment key is never generated by the application: losing it
must fail closed rather than silently creating an unprotected session store.
"""
import hashlib
import hmac
import json
import os
from pathlib import Path
import re
import sqlite3
import time
from contextlib import contextmanager

from cryptography.fernet import Fernet, InvalidToken

LIFETIME = 30 * 24 * 3600
MAX_SESSIONS = 1024
MAX_PER_ACCOUNT = 20
KEY_FILE = "/run/veyro/remembered-session-key"
DATABASE = "/var/lib/veyro-webmail/remembered-sessions.sqlite3"
TOKEN = re.compile(r"[A-Za-z0-9_-]{48}\Z")


class Unavailable(Exception):
    """Storage/key unavailable; callers return a generic retryable failure."""


class Full(Exception):
    """Bounded session capacity reached; never evict another active login."""


class Store:
    def __init__(self, database=DATABASE, key_file=KEY_FILE, *, clock=time.time):
        self.database = Path(database)
        self.key_file = Path(key_file)
        self.clock = clock

    def cipher(self):
        try:
            key = self.key_file.read_bytes().strip()
            return Fernet(key), key
        except (OSError, ValueError, TypeError):
            raise Unavailable() from None

    @contextmanager
    def connection(self):
        db = None
        try:
            # Creation mode must be private before SQLite writes any credential.
            fd = os.open(self.database, os.O_CREAT | os.O_RDWR, 0o600)
            os.close(fd)
            os.chmod(self.database, 0o600)
            db = sqlite3.connect(self.database, timeout=5)
            db.execute("PRAGMA secure_delete=ON")
            db.execute("PRAGMA max_page_count=8192")  # At most ~32 MiB with 4 KiB pages.
            db.execute("""CREATE TABLE IF NOT EXISTS remembered_sessions (
                token_hash TEXT PRIMARY KEY, account_hash TEXT NOT NULL,
                expires INTEGER NOT NULL, payload BLOB NOT NULL
            )""")
            db.execute("CREATE INDEX IF NOT EXISTS remembered_account ON remembered_sessions(account_hash)")
            db.execute("BEGIN IMMEDIATE")
            db.execute("DELETE FROM remembered_sessions WHERE expires<=?", (int(self.clock()),))
            yield db
            db.commit()
        except (OSError, sqlite3.Error):
            raise Unavailable() from None
        finally:
            if db is not None:
                db.close()

    @staticmethod
    def token_hash(token):
        return hashlib.sha256(token.encode("ascii")).hexdigest()

    @staticmethod
    def account_hash(address, key):
        return hmac.new(key, address.encode(), hashlib.sha256).hexdigest()

    def put(self, token, *, email, password, csrf, generation, replaces=""):
        if not isinstance(token, str) or not TOKEN.fullmatch(token):
            raise ValueError("Invalid generated session token")
        cipher, key = self.cipher()
        issued = int(self.clock())
        expires = issued + LIFETIME
        digest = self.token_hash(token)
        index = self.account_hash(email, key)
        payload = dict(token_hash=digest, email=email, password=password, csrf=csrf,
                       generation=generation, issued=issued, expires=expires)
        encrypted = cipher.encrypt(json.dumps(payload, separators=(",", ":")).encode())
        with self.connection() as db:
            if TOKEN.fullmatch(replaces):
                db.execute("DELETE FROM remembered_sessions WHERE token_hash=?", (self.token_hash(replaces),))
            total = db.execute("SELECT COUNT(*) FROM remembered_sessions").fetchone()[0]
            count = db.execute("SELECT COUNT(*) FROM remembered_sessions WHERE account_hash=?", (index,)).fetchone()[0]
            if total >= MAX_SESSIONS or count >= MAX_PER_ACCOUNT:
                raise Full()
            db.execute("INSERT INTO remembered_sessions VALUES (?, ?, ?, ?)", (digest, index, expires, encrypted))
        return expires

    def get(self, token):
        if not isinstance(token, str) or not TOKEN.fullmatch(token) or not self.database.exists():
            return None
        digest = self.token_hash(token)
        with self.connection() as db:
            row = db.execute("SELECT account_hash, expires, payload FROM remembered_sessions WHERE token_hash=?", (digest,)).fetchone()
            if row is None:
                return None
            cipher, key = self.cipher()
            try:
                payload = json.loads(cipher.decrypt(row[2]))
                if (not isinstance(payload, dict) or payload.get("token_hash") != digest or
                        payload.get("expires") != row[1] or type(payload.get("issued")) is not int or
                        row[1] - payload["issued"] != LIFETIME or payload["issued"] > int(self.clock()) or
                        not isinstance(payload.get("email"), str) or not 1 <= len(payload["email"]) <= 254 or
                        self.account_hash(payload["email"], key) != row[0] or
                        not isinstance(payload.get("password"), str) or not 1 <= len(payload["password"]) <= 1024 or
                        not isinstance(payload.get("csrf"), str) or not re.fullmatch(r"[A-Za-z0-9_-]{43}", payload["csrf"]) or
                        not isinstance(payload.get("generation"), str) or not re.fullmatch(r"[a-fA-F0-9]{64}", payload["generation"])):
                    raise ValueError()
                return payload
            except (InvalidToken, ValueError, TypeError, KeyError):
                # Corrupt/swapped rows cannot become authenticated sessions.
                db.execute("DELETE FROM remembered_sessions WHERE token_hash=?", (digest,))
                return None

    def delete(self, token):
        if not isinstance(token, str) or not TOKEN.fullmatch(token) or not self.database.exists():
            return
        with self.connection() as db:
            db.execute("DELETE FROM remembered_sessions WHERE token_hash=?", (self.token_hash(token),))

    def delete_account(self, address):
        if not self.database.exists():
            return
        _, key = self.cipher()
        with self.connection() as db:
            db.execute("DELETE FROM remembered_sessions WHERE account_hash=?", (self.account_hash(address, key),))

    def purge(self):
        if self.database.exists():
            with self.connection():
                pass
